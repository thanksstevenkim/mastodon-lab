import {readFileSync, readdirSync} from 'node:fs';

// Docusaurus infers incident titles as "Ticket ID" because the source reports
// use field-style headings. Generate friendly sidebar labels from the real
// "# Ticket ID" and "# Title" fields without changing the source Markdown.
function incidentSidebarItems() {
  const files = readdirSync(new URL('../incidents/', import.meta.url))
    .filter((file) => file.endsWith('.md'))
    .sort();

  return files.map((file) => {
    const id = file.slice(0, -3);
    const lines = readFileSync(new URL('../incidents/' + file, import.meta.url), 'utf8').split(/\r?\n/);
    const field = (name) => {
      const i = lines.findIndex((line) => line.trim() === '# ' + name);
      return i < 0 ? '' : lines.slice(i + 1).find((line) => line.trim().length > 0)?.trim() || '';
    };

    const ticket = field('Ticket ID');
    const title = field('Title');
    const fallback = id.replace(/^\d+-/, '').replace(/-/g, ' ');
    const displayTitle = title && !title.startsWith('#') ? title : fallback;
    const ticketId = /^SUP-\d+$/.test(ticket) ? ticket : null;
    return {
      type: 'doc',
      id: 'incidents/' + id,
      label: id.startsWith('000-') ? 'Incident report template' : displayTitle,
      ...(!id.startsWith('000-') && ticketId ? {customProps: {ticketId}} : {}),
    };
  });
}

// All other categories still use automatic navigation. Original Markdown stays
